#!/usr/bin/env bash
# Builds the MAGPIE static libraries that the magpie/ cgo package links:
#
#   build/magpie/libmagpie_b15.a   BOARD_DIM=15
#   build/magpie/libmagpie_b21.a   BOARD_DIM=21, every global symbol renamed
#                                  mg21_* so both link into one binary
#
# MAGPIE fixes BOARD_DIM at compile time, so a super (21x21) board needs a
# second build. The rename is done at compile time with a forced-include header
# of #defines generated from the b15 build's symbol table, which works on LTO
# objects too (objcopy can't rename inside LTO bitcode).
#
# MAGPIE_MARCH picks the instruction set (default native; releases pass a
# portable one, e.g. x86-64-v2). MAGPIE_CC overrides the compiler.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/third_party/magpie"
OUT="$ROOT/build/magpie"
MARCH="${MAGPIE_MARCH:-native}"
CC="${MAGPIE_CC:-${CC:-cc}}"

if [ ! -f "$SRC/Makefile" ]; then
	echo "third_party/magpie is missing; run: git submodule update --init" >&2
	exit 1
fi
mkdir -p "$OUT"

# -fPIC: Go links PIE executables on several platforms.
BASE_CFLAGS="-O3 -march=$MARCH -DNDEBUG -Wall -Wno-trigraphs -fPIC -DRACK_SIZE=7 -DMAGPIE_BUILD_TARGET=\\\"$MARCH\\\""

build() {
	local dim="$1" extra="$2"
	# BUILD only keys MAGPIE's object directory here; CFLAGS on the command line
	# replaces the flavor's flags entirely.
	make -C "$SRC" --no-print-directory BUILD="macondo-$MARCH" CC="$CC" \
		BOARD_DIM="$dim" CFLAGS="$BASE_CFLAGS -DBOARD_DIM=$dim $extra" \
		libmagpie_core.a >"$OUT/build-b$dim.log" 2>&1 || {
		tail -40 "$OUT/build-b$dim.log" >&2
		exit 1
	}
	mv "$SRC/libmagpie_core.a" "$OUT/libmagpie_b$dim.a"
}

build 15 ""

# Mach-O prefixes every C symbol with an underscore; the #defines below need
# the C names.
UNDERSCORE=""
if [ "$(uname -s)" = "Darwin" ]; then
	UNDERSCORE="_"
fi

# Every global symbol the b15 library defines, as a #define to its mg21_ name.
RENAME="$OUT/mg21_rename.h"
{
	echo "// Generated by scripts/build_magpie.sh; do not edit."
	echo "#ifndef MG21_RENAME_H"
	echo "#define MG21_RENAME_H"
	nm --defined-only -g "$OUT/libmagpie_b15.a" 2>/dev/null |
		awk -v u="$UNDERSCORE" 'NF == 3 && $2 ~ /^[TDBRCVWS]$/ { s = $3; if (u != "" && substr(s, 1, 1) == u) s = substr(s, 2); print s }' |
		sort -u | awk '{ printf "#define %s mg21_%s\n", $1, $1 }'
	echo "#endif"
} >"$RENAME.tmp"
mv "$RENAME.tmp" "$RENAME"

build 21 "-include $RENAME"

# The b21 library must define no unprefixed symbol, or the link would pick one
# copy of it for both board sizes.
leaked="$(nm --defined-only -g "$OUT/libmagpie_b21.a" |
	awk -v u="$UNDERSCORE" 'NF == 3 && $2 ~ /^[TDBRCVWS]$/ { s = $3; if (u != "" && substr(s, 1, 1) == u) s = substr(s, 2); if (s !~ /^mg21_/) print s }' | sort -u)"
if [ -n "$leaked" ]; then
	echo "libmagpie_b21.a defines unprefixed symbols:" >&2
	echo "$leaked" >&2
	exit 1
fi

git -C "$SRC" rev-parse HEAD >"$OUT/MAGPIE_COMMIT"
echo "built $OUT/libmagpie_b15.a and libmagpie_b21.a (MAGPIE $(cut -c1-8 "$OUT/MAGPIE_COMMIT"), -march=$MARCH)"
