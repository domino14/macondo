package main

import (
	"fmt"
	"math"
	"math/rand"
)

func main() {
	fmt.Println("//! Generated by tools/gogolden/rand from Go's math/rand; see gorand.zig's test.")
	fmt.Println("pub const Case = struct { seed: i64, int63: []const i64, float64: []const f64 };")
	fmt.Println("pub const cases = [_]Case{")
	for _, s := range []int64{0, -1, 9223372036854775807, -9223372036854775808, 0x1234567890abcdef} {
		r := rand.New(rand.NewSource(s))
		fmt.Printf("    .{ .seed = %d, .int63 = &.{", s)
		for i := 0; i < 620; i++ {
			fmt.Printf(" %d,", r.Int63())
		}
		fmt.Printf(" }, .float64 = &.{")
		for i := 0; i < 20; i++ {
			fmt.Printf(" @bitCast(@as(u64, %d)),", math.Float64bits(r.Float64()))
		}
		fmt.Println(" } },")
	}
	fmt.Println("};")
}
