package main

import (
	"fmt"
	"math/rand"
	"sort"
	"strings"
)

func main() {
	r := rand.New(rand.NewSource(7))
	type pair struct{ key, id int }
	var cases []string
	maxLen := 0
	gen := func(keys []int) {
		ps := make([]pair, len(keys))
		for i, k := range keys {
			ps[i] = pair{k, i}
		}
		sort.Slice(ps, func(i, j int) bool { return ps[i].key < ps[j].key })
		ks := make([]string, len(keys))
		ids := make([]string, len(keys))
		for i := range keys {
			ks[i] = fmt.Sprint(keys[i])
			ids[i] = fmt.Sprint(ps[i].id)
		}
		if len(keys) > maxLen {
			maxLen = len(keys)
		}
		cases = append(cases, fmt.Sprintf("    .{ .keys = &.{ %s }, .ids = &.{ %s } },", strings.Join(ks, ", "), strings.Join(ids, ", ")))
	}
	for _, n := range []int{0, 1, 5, 12, 13, 20, 49, 50, 51, 100, 200, 400} {
		for _, distinct := range []int{2, 5, 50, 1000000} {
			keys := make([]int, n)
			for i := range keys {
				keys[i] = r.Intn(distinct)
			}
			gen(keys)
		}
		// Sorted, reversed, mostly sorted, organ pipe.
		inc := make([]int, n)
		dec := make([]int, n)
		pipe := make([]int, n)
		for i := 0; i < n; i++ {
			inc[i] = i / 3
			dec[i] = (n - i) / 2
			pipe[i] = min(i, n-i)
		}
		gen(inc)
		gen(dec)
		gen(pipe)
		if n > 4 {
			ms := append([]int(nil), inc...)
			ms[1], ms[n-2] = ms[n-2], ms[1]
			gen(ms)
		}
	}
	fmt.Println("//! Generated by tools/gogolden/sort from Go's sort.Slice; see gosort.zig's test.")
	fmt.Printf("pub const max_len = %d;\n", maxLen)
	fmt.Println("pub const Case = struct { keys: []const u32, ids: []const u32 };")
	fmt.Println("pub const cases = [_]Case{")
	for _, c := range cases {
		fmt.Println(c)
	}
	fmt.Println("};")
}
